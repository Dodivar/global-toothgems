-- =============================================================================
-- Migration — Product options combined into variants (colour × plug…)
-- =============================================================================
-- Until now a product's variants were a flat list: one name each ("Argent",
-- "Noir"). The curing lamp is now sold in two colours AND with a European or
-- an American plug, each combination a different article on the shelf
-- (decided by the owner on 2026-10-29: same price for every combination,
-- stock kept per combination). A flat list of four names ("Argent · Prise
-- EU"…) would show four mixed buttons and link the silver photo twice.
--
-- Model (decision 119 in supabase/README.md):
--
--   product_options                   an axis of a product: "Couleur", "Prise"
--     product_option_translations     its English name
--   product_option_values             a value of an axis: "Argent" (+ colour
--                                     dot), "Prise EU"
--     product_option_value_translations
--   product_variant_option_values     variant ↔ the value it has on each axis
--   product_media.option_value_id     a photo showing a value (the silver
--                                     photo shows "Argent", whatever the plug)
--
-- A variant stays what is sold: its own SKU, price, stock row, orders,
-- invoices and back-in-stock alerts — nothing downstream changes. The
-- options only describe which value each variant has on each axis, so the
-- product page offers one row of choices per axis.
--
-- admin_save_product() gains one OPTIONAL input, sent with `custom_variants`:
--
--   variant_options   absent        options left as they are (refused when
--                                   the product has options: an admin
--                                   deployed before this migration would
--                                   otherwise rename its variants);
--                     []            the product has no options (any it had
--                                   are deleted; variants keep their names);
--                     a list        the complete, ordered axes:
--     [{ id, name, name_en, values: [{ id, name, name_en, swatch }] }]
--       1–3 axes, 1–30 values each; ids generated by the browser like a
--       variant's; names 1–60 characters, unique within their list (case
--       insensitive), English optional (falls back to French); swatch
--       '#rrggbb' or null.
--   custom_variants[].option_values   with options: one value id per axis,
--       in axis order, each combination once. The variant's name (French and
--       English, values joined by " · ") and its colour dot (the first value
--       with one) are then derived here; the sent ones are ignored.
--   media[].option_value_id           when the key is present: the value this
--       photo shows (a value of this product), null = none. A photo shows a
--       variant or a value, not both.
--
-- The function returns `variant_options: true` when the payload carried the
-- key. Everything else is unchanged from `…_product_specs_faq.sql`.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Tables
-- -----------------------------------------------------------------------------
create table public.product_options (
  id         uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete cascade,
  name       text not null check (char_length(btrim(name)) between 1 and 60),
  position   integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null
);

comment on table public.product_options is
  'An axis a product is offered on (French name): "Couleur", "Prise". Its variants each have one value per axis (product_variant_option_values).';

create index product_options_product_idx on public.product_options (product_id, position);

create table public.product_option_values (
  id         uuid primary key default gen_random_uuid(),
  option_id  uuid not null references public.product_options (id) on delete cascade,
  name       text not null check (char_length(btrim(name)) between 1 and 60),
  swatch     text check (swatch ~ '^#[0-9a-f]{6}$'),
  position   integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  -- Target of the variant link's composite key: a value of the stated axis.
  constraint product_option_values_option_unique unique (id, option_id)
);

comment on table public.product_option_values is
  'A value of a product axis (French name), with an optional colour dot: "Argent" #d9d9d9, "Prise EU".';

create index product_option_values_option_idx on public.product_option_values (option_id, position);

create table public.product_variant_option_values (
  variant_id uuid not null references public.product_variants (id) on delete cascade,
  option_id  uuid not null references public.product_options (id) on delete cascade,
  value_id   uuid not null,
  primary key (variant_id, option_id),
  constraint product_variant_option_values_value_fkey
    foreign key (value_id, option_id) references public.product_option_values (id, option_id) on delete cascade
);

comment on table public.product_variant_option_values is
  'The value a variant has on each axis of its product: one row per (variant, axis).';

create index product_variant_option_values_value_idx on public.product_variant_option_values (value_id, option_id);
create index product_variant_option_values_option_idx on public.product_variant_option_values (option_id);

create table public.product_option_translations (
  option_id  uuid not null references public.product_options (id) on delete cascade,
  locale     text not null references public.languages (code) on update cascade,
  name       text not null check (char_length(btrim(name)) between 1 and 60),
  status     text not null default 'draft' check (status in ('draft', 'published')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id) on delete set null,
  primary key (option_id, locale)
);

create table public.product_option_value_translations (
  value_id   uuid not null references public.product_option_values (id) on delete cascade,
  locale     text not null references public.languages (code) on update cascade,
  name       text not null check (char_length(btrim(name)) between 1 and 60),
  status     text not null default 'draft' check (status in ('draft', 'published')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id) on delete set null,
  primary key (value_id, locale)
);

create index product_option_translations_locale_idx on public.product_option_translations (locale);
create index product_option_value_translations_locale_idx on public.product_option_value_translations (locale);

-- A photo shows a variant, or a value of an axis (all its combinations), or neither.
alter table public.product_media
  add column option_value_id uuid references public.product_option_values (id) on delete set null,
  add constraint product_media_one_subject check (num_nonnulls(variant_id, option_value_id) <= 1);

comment on column public.product_media.option_value_id is
  'The option value this photo shows ("Argent"), whatever the other axes; null = none. Never set with variant_id.';

create index product_media_option_value_idx on public.product_media (option_value_id) where option_value_id is not null;

create trigger product_options_audit
  before insert or update on public.product_options
  for each row execute function private.set_audit_columns();
create trigger product_option_values_audit
  before insert or update on public.product_option_values
  for each row execute function private.set_audit_columns();

do $$
declare
  t text;
begin
  foreach t in array array['product_option_translations', 'product_option_value_translations']
  loop
    execute format(
      'create trigger %I before insert or update on public.%I
         for each row execute function private.reject_default_locale_translation()',
      t || '_not_default_locale', t);
    execute format(
      'create trigger %I before insert or update on public.%I
         for each row execute function private.set_translation_audit()',
      t || '_audit', t);
  end loop;
end;
$$;

-- -----------------------------------------------------------------------------
-- 2. Privileges + RLS: visitors read the options of active products (and
--    published translations, links of active variants); staff read
--    everything; manage_products writes (in practice through
--    admin_save_product()).
-- -----------------------------------------------------------------------------
alter table public.product_options enable row level security;
alter table public.product_option_values enable row level security;
alter table public.product_variant_option_values enable row level security;
alter table public.product_option_translations enable row level security;
alter table public.product_option_value_translations enable row level security;

revoke truncate, references, trigger on public.product_options, public.product_option_values,
  public.product_variant_option_values, public.product_option_translations,
  public.product_option_value_translations from anon, authenticated;
revoke insert, update, delete on public.product_options, public.product_option_values,
  public.product_variant_option_values, public.product_option_translations,
  public.product_option_value_translations from anon;
grant select on public.product_options, public.product_option_values,
  public.product_variant_option_values, public.product_option_translations,
  public.product_option_value_translations to anon, authenticated;
grant insert, update, delete on public.product_options, public.product_option_values,
  public.product_variant_option_values, public.product_option_translations,
  public.product_option_value_translations to authenticated;

create policy "product_options: public reads active products, staff read all"
  on public.product_options for select to anon, authenticated
  using (
    exists (select 1 from public.products p
             where p.id = product_options.product_id and p.status = 'active')
    or (select private.is_staff())
  );

create policy "product_option_values: public reads active products, staff read all"
  on public.product_option_values for select to anon, authenticated
  using (
    exists (select 1 from public.product_options o
              join public.products p on p.id = o.product_id
             where o.id = product_option_values.option_id and p.status = 'active')
    or (select private.is_staff())
  );

create policy "product_variant_option_values: public reads active variants, staff read all"
  on public.product_variant_option_values for select to anon, authenticated
  using (
    exists (select 1 from public.product_variants v
              join public.products p on p.id = v.product_id
             where v.id = product_variant_option_values.variant_id
               and v.is_active and p.status = 'active')
    or (select private.is_staff())
  );

create policy "product_option_translations: public reads published, staff read all"
  on public.product_option_translations for select to anon, authenticated
  using (
    (status = 'published' and exists (
      select 1 from public.product_options o
        join public.products p on p.id = o.product_id
       where o.id = product_option_translations.option_id and p.status = 'active'))
    or (select private.is_staff())
  );

create policy "product_option_value_translations: public reads published, staff read all"
  on public.product_option_value_translations for select to anon, authenticated
  using (
    (status = 'published' and exists (
      select 1 from public.product_option_values ov
        join public.product_options o on o.id = ov.option_id
        join public.products p on p.id = o.product_id
       where ov.id = product_option_value_translations.value_id and p.status = 'active'))
    or (select private.is_staff())
  );

do $$
declare
  t text;
begin
  foreach t in array array['product_options', 'product_option_values', 'product_variant_option_values',
                           'product_option_translations', 'product_option_value_translations']
  loop
    execute format(
      'create policy %I on public.%I for insert to authenticated
         with check ((select private.has_permission(''manage_products'')))',
      t || ': staff insert', t);
    execute format(
      'create policy %I on public.%I for update to authenticated
         using ((select private.has_permission(''manage_products'')))
         with check ((select private.has_permission(''manage_products'')))',
      t || ': staff update', t);
    execute format(
      'create policy %I on public.%I for delete to authenticated
         using ((select private.has_permission(''manage_products'')))',
      t || ': staff delete', t);
  end loop;
end;
$$;

-- -----------------------------------------------------------------------------
-- 3. admin_save_product(): `variant_options`, derived variant names, photos
--    of a value
-- -----------------------------------------------------------------------------
create or replace function public.admin_save_product(p_product jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id        uuid := (p_product ->> 'id')::uuid;
  v_price     text := p_product ->> 'price';
  v_compare   text := nullif(p_product ->> 'compare_at_price', '');
  v_inventory jsonb := coalesce(p_product -> 'inventory', '{}'::jsonb);
  v_media     jsonb := coalesce(p_product -> 'media', '[]'::jsonb);
  v_variants  jsonb := p_product -> 'variants';
  v_custom    jsonb := p_product -> 'custom_variants';
  v_en        jsonb := p_product -> 'translations' -> 'en';
  v_specs     jsonb := p_product -> 'specs';
  v_slug      text;
  v_base      text;
  v_n         integer := 1;
  v_keep      uuid[];
  v_removed   text[];
  v_item      jsonb;
  v_media_id  uuid;
  v_position  integer := 0;
  -- variants
  v_sku        text;
  v_pack       integer;
  v_ss         integer;
  v_mm         jsonb;
  v_mm_fr      text;
  v_mm_en      text;
  v_mm_sku     text;
  v_kind       text;
  v_kinds      text[] := '{}';
  v_vprice     text;
  v_name_fr    text;
  v_name_en    text;
  v_vsku       text;
  v_variant_id uuid;
  v_variant_ids uuid[] := '{}';
  -- custom variants
  v_custom_ids uuid[] := '{}';
  v_swatch     text;
  v_owner      uuid;
  v_code       text;
  v_media_variant uuid;
  -- options (axes) and their values
  v_options    jsonb := p_product -> 'variant_options';
  v_opt        jsonb;
  v_val        jsonb;
  v_opt_id     uuid;
  v_val_id     uuid;
  v_option_ids uuid[] := '{}';
  v_value_ids  uuid[] := '{}';
  v_value_axis jsonb := '{}'::jsonb;  -- value id -> axis index (0-based)
  v_value_info jsonb := '{}'::jsonb;  -- value id -> { name, name_en, swatch }
  v_axes       integer := 0;
  v_combo      text;
  v_combos     text[] := '{}';
  v_norm       jsonb;
  v_picked     jsonb;
  v_vpos       integer;
  v_media_value uuid;
begin
  if not private.has_permission('manage_products') then
    raise exception 'admin_save_product: permission denied' using errcode = '42501';
  end if;
  if v_id is null then
    raise exception 'admin_save_product: id is required' using errcode = '22023';
  end if;
  if v_price is null or v_price !~ '^\d{1,10}(\.\d{1,2})?$' then
    raise exception 'admin_save_product: invalid price' using errcode = '22023';
  end if;
  if v_compare is not null and v_compare !~ '^\d{1,10}(\.\d{1,2})?$' then
    raise exception 'admin_save_product: invalid compare_at_price' using errcode = '22023';
  end if;
  if jsonb_typeof(v_media) <> 'array' then
    raise exception 'admin_save_product: media must be an array' using errcode = '22023';
  end if;
  if v_variants is not null and jsonb_typeof(v_variants) = 'null' then
    v_variants := null;
  end if;
  if v_variants is not null and jsonb_typeof(v_variants) <> 'array' then
    raise exception 'admin_save_product: variants must be an array' using errcode = '22023';
  end if;
  if v_custom is not null and jsonb_typeof(v_custom) = 'null' then
    v_custom := null;
  end if;
  if v_custom is not null and jsonb_typeof(v_custom) <> 'array' then
    raise exception 'admin_save_product: custom_variants must be an array' using errcode = '22023';
  end if;
  if v_variants is not null and v_custom is not null then
    raise exception 'admin_save_product: send either variants or custom_variants, not both' using errcode = '22023';
  end if;
  if v_options is not null and jsonb_typeof(v_options) = 'null' then
    v_options := null;
  end if;
  if v_options is not null and (v_custom is null or jsonb_typeof(v_options) <> 'array') then
    raise exception 'admin_save_product: variant_options must be an array sent with custom_variants' using errcode = '22023';
  end if;

  -- Characteristics: five optional { fr, en } values, 120 characters at most.
  if v_specs is not null and jsonb_typeof(v_specs) = 'null' then
    v_specs := null;
  end if;
  if v_specs is not null and (
       jsonb_typeof(v_specs) <> 'object'
       or exists (select 1 from jsonb_object_keys(v_specs) k
                   where k not in ('material', 'center', 'back', 'packaging', 'wear'))
       or exists (select 1 from jsonb_each(v_specs) e
                   where jsonb_typeof(e.value) not in ('object', 'null')
                      or (jsonb_typeof(e.value) = 'object' and (
                            exists (select 1 from jsonb_object_keys(e.value) l where l not in ('fr', 'en'))
                            or char_length(btrim(coalesce(e.value ->> 'fr', ''))) > 120
                            or char_length(btrim(coalesce(e.value ->> 'en', ''))) > 120)))) then
    raise exception 'admin_save_product: invalid characteristics' using errcode = '22023';
  end if;

  -- 1. Product row ------------------------------------------------------------
  if exists (select 1 from public.products where id = v_id) then
    update public.products
       set category_id       = (p_product ->> 'category_id')::uuid,
           family_id         = case when p_product ? 'family_id'
                                    then nullif(p_product ->> 'family_id', '')::uuid
                                    else family_id end,
           sku               = nullif(p_product ->> 'sku', ''),
           name              = p_product ->> 'name',
           short_description = nullif(p_product ->> 'short_description', ''),
           description       = nullif(p_product ->> 'description', ''),
           price             = v_price::numeric(12, 2),
           compare_at_price  = v_compare::numeric(12, 2),
           status            = p_product ->> 'status',
           metadata          = metadata || coalesce(p_product -> 'metadata', '{}'::jsonb)
     where id = v_id
    returning slug into v_slug;
  else
    -- The slug is the storefront URL: set once, made unique with a suffix.
    v_base := p_product ->> 'slug';
    v_slug := v_base;
    while exists (select 1 from public.products where slug = v_slug) loop
      v_n := v_n + 1;
      v_slug := v_base || '-' || v_n;
    end loop;

    insert into public.products
      (id, category_id, family_id, sku, name, slug, short_description, description,
       price, compare_at_price, status, metadata)
    values
      (v_id, (p_product ->> 'category_id')::uuid, nullif(p_product ->> 'family_id', '')::uuid,
       nullif(p_product ->> 'sku', ''),
       p_product ->> 'name', v_slug,
       nullif(p_product ->> 'short_description', ''), nullif(p_product ->> 'description', ''),
       v_price::numeric(12, 2), v_compare::numeric(12, 2),
       p_product ->> 'status', coalesce(p_product -> 'metadata', '{}'::jsonb));
  end if;

  -- 2. English translation (published on save; absent = storefront falls back
  --    to French) ---------------------------------------------------------------
  if coalesce(trim(v_en ->> 'name'), '') <> '' then
    v_base := nullif(v_en ->> 'slug', '');
    v_n := 1;
    if not exists (select 1 from public.product_translations where product_id = v_id and locale = 'en')
       and v_base is not null then
      v_slug := v_base;
      while exists (select 1 from public.product_translations where locale = 'en' and slug = v_slug) loop
        v_n := v_n + 1;
        v_slug := v_base || '-' || v_n;
      end loop;
    else
      v_slug := null;  -- keep the existing English URL
    end if;

    insert into public.product_translations
      (product_id, locale, name, slug, short_description, description, status)
    values
      (v_id, 'en', v_en ->> 'name', v_slug,
       nullif(v_en ->> 'short_description', ''), nullif(v_en ->> 'description', ''), 'published')
    on conflict (product_id, locale) do update
       set name              = excluded.name,
           short_description = excluded.short_description,
           description       = excluded.description,
           status            = 'published';
  else
    delete from public.product_translations where product_id = v_id and locale = 'en';
  end if;

  -- 2b. Characteristics (only when the payload carries them): French on the
  --     product, English on its English row when there is one ---------------
  if v_specs is not null then
    update public.products
       set spec_material  = nullif(btrim(v_specs -> 'material'  ->> 'fr'), ''),
           spec_center    = nullif(btrim(v_specs -> 'center'    ->> 'fr'), ''),
           spec_back      = nullif(btrim(v_specs -> 'back'      ->> 'fr'), ''),
           spec_packaging = nullif(btrim(v_specs -> 'packaging' ->> 'fr'), ''),
           spec_wear      = nullif(btrim(v_specs -> 'wear'      ->> 'fr'), '')
     where id = v_id;
    update public.product_translations
       set spec_material  = nullif(btrim(v_specs -> 'material'  ->> 'en'), ''),
           spec_center    = nullif(btrim(v_specs -> 'center'    ->> 'en'), ''),
           spec_back      = nullif(btrim(v_specs -> 'back'      ->> 'en'), ''),
           spec_packaging = nullif(btrim(v_specs -> 'packaging' ->> 'en'), ''),
           spec_wear      = nullif(btrim(v_specs -> 'wear'      ->> 'en'), '')
     where product_id = v_id and locale = 'en';
  end if;

  -- 3. Pack / size options (only when the payload carries them) ---------------
  if v_variants is not null then
    -- Only pack/size variants are managed here: a product whose variants are
    -- something else (colours, boxes…) must not lose them to this editor.
    if exists (
      select 1 from public.product_variants pv
       where pv.product_id = v_id
         and (pv.attributes = '{}'::jsonb
              or exists (select 1 from jsonb_object_keys(pv.attributes) k where k not in ('pack', 'ss', 'mm')))
    ) then
      raise exception 'admin_save_product: this product has other kinds of variants' using errcode = '22023';
    end if;

    v_sku := (select sku from public.products where id = v_id);
    v_position := 0;

    for v_item in select value from jsonb_array_elements(v_variants) loop
      if jsonb_typeof(v_item) <> 'object' then
        raise exception 'admin_save_product: invalid variant' using errcode = '22023';
      end if;
      if coalesce(v_item ->> 'pack', '') !~ '^\d{0,5}$' then
        raise exception 'admin_save_product: invalid pack size' using errcode = '22023';
      end if;
      if coalesce(v_item ->> 'ss', '') !~ '^\d{1,2}$' and coalesce(v_item ->> 'ss', '') <> '' then
        raise exception 'admin_save_product: invalid stone size' using errcode = '22023';
      end if;
      v_pack := nullif(v_item ->> 'pack', '')::integer;
      v_ss   := nullif(v_item ->> 'ss', '')::integer;
      -- Dimensions in millimetres: one value (diameter / longest side) or two
      -- (width × length), each 0.5–30 mm to a tenth, stored ascending.
      v_mm := v_item -> 'mm';
      if v_mm is not null and jsonb_typeof(v_mm) = 'null' then
        v_mm := null;
      end if;
      if v_mm is not null then
        if jsonb_typeof(v_mm) <> 'array' or jsonb_array_length(v_mm) not between 1 and 2
           or exists (select 1 from jsonb_array_elements(v_mm) d
                       where jsonb_typeof(d) <> 'number'
                          or (d #>> '{}')::numeric not between 0.5 and 30
                          or (d #>> '{}')::numeric <> round((d #>> '{}')::numeric, 1)) then
          raise exception 'admin_save_product: invalid dimensions' using errcode = '22023';
        end if;
        select jsonb_agg(to_jsonb(trim_scale(x)) order by x),
               string_agg(replace(trim_scale(x)::text, '.', ','), ' × ' order by x) || ' mm',
               string_agg(trim_scale(x)::text, ' × ' order by x) || ' mm',
               string_agg(replace(trim_scale(x)::text, '.', 'P'), 'X' order by x) || 'MM'
          into v_mm, v_mm_fr, v_mm_en, v_mm_sku
          from (select (d #>> '{}')::numeric as x from jsonb_array_elements(v_mm) d) dims;
      else
        v_mm_fr := null;
        v_mm_en := null;
        v_mm_sku := null;
      end if;
      if v_ss is not null and v_mm is not null then
        raise exception 'admin_save_product: a variant has a stone size or dimensions, not both' using errcode = '22023';
      end if;
      if v_pack is null and v_ss is null and v_mm is null then
        raise exception 'admin_save_product: a variant needs a pack or a size' using errcode = '22023';
      end if;
      -- One way of sizing per product: SS gauges or millimetre dimensions.
      v_kind := case when v_ss is not null then 'ss' when v_mm is not null then 'mm' end;
      if v_kind is not null and not (v_kind = any (v_kinds)) then
        v_kinds := array_append(v_kinds, v_kind);
      end if;
      if cardinality(v_kinds) > 1 then
        raise exception 'admin_save_product: a product is sized in SS or in millimetres, not both' using errcode = '22023';
      end if;
      if v_pack is not null and v_pack not between 1 and 10000 then
        raise exception 'admin_save_product: pack size must be between 1 and 10000' using errcode = '22023';
      end if;
      if v_ss is not null and v_ss not between 1 and 60 then
        raise exception 'admin_save_product: invalid stone size' using errcode = '22023';
      end if;
      v_vprice := nullif(v_item ->> 'price', '');
      if v_vprice is not null and v_vprice !~ '^\d{1,10}(\.\d{1,2})?$' then
        raise exception 'admin_save_product: invalid variant price' using errcode = '22023';
      end if;

      v_name_fr := concat_ws(' · ', 'Pack de ' || v_pack, 'SS' || v_ss, v_mm_fr);
      v_name_en := concat_ws(' · ', 'Pack of ' || v_pack, 'SS' || v_ss, v_mm_en);
      v_vsku := case when v_sku is null then null
                     else v_sku || concat('-P' || v_pack, '-SS' || v_ss, '-' || v_mm_sku) end;
      if v_vsku is not null and v_vsku !~ '^[A-Z0-9][A-Z0-9-]{1,63}$' then
        raise exception 'admin_save_product: product SKU too long for its option SKUs' using errcode = '22023';
      end if;

      -- The same combination twice in one payload would silently merge.
      select pv.id into v_variant_id
        from public.product_variants pv
       where pv.product_id = v_id
         and pv.attributes -> 'pack' is not distinct from to_jsonb(v_pack)
         and pv.attributes -> 'ss'   is not distinct from to_jsonb(v_ss)
         and pv.attributes -> 'mm'   is not distinct from v_mm;
      if v_variant_id = any (v_variant_ids) then
        raise exception 'admin_save_product: duplicate option %', v_name_en using errcode = '22023';
      end if;

      if v_variant_id is not null then
        update public.product_variants
           set name       = v_name_fr,
               sku        = v_vsku,
               price      = v_vprice::numeric(12, 2),
               is_active  = true,
               position   = v_position
         where id = v_variant_id;
      else
        insert into public.product_variants (product_id, name, sku, attributes, price, is_active, position)
        values (v_id, v_name_fr, v_vsku,
                jsonb_strip_nulls(jsonb_build_object('pack', v_pack, 'ss', v_ss, 'mm', v_mm)),
                v_vprice::numeric(12, 2), true, v_position)
        returning id into v_variant_id;
      end if;

      insert into public.product_variant_translations (variant_id, locale, name, status)
      values (v_variant_id, 'en', v_name_en, 'published')
      on conflict (variant_id, locale) do update set name = excluded.name, status = 'published';

      update public.inventory_items
         set track_inventory     = coalesce((v_item ->> 'track_inventory')::boolean, track_inventory),
             quantity_on_hand    = coalesce((v_item ->> 'quantity_on_hand')::integer, quantity_on_hand),
             low_stock_threshold = coalesce((v_item ->> 'low_stock_threshold')::integer, low_stock_threshold)
       where variant_id = v_variant_id;
      if not found then
        insert into public.inventory_items (variant_id, track_inventory, quantity_on_hand, low_stock_threshold)
        values (v_variant_id,
                coalesce((v_item ->> 'track_inventory')::boolean, true),
                coalesce((v_item ->> 'quantity_on_hand')::integer, 0),
                coalesce((v_item ->> 'low_stock_threshold')::integer, 5));
      end if;

      v_variant_ids := array_append(v_variant_ids, v_variant_id);
      v_variant_id := null;
      v_position := v_position + 1;
    end loop;

    -- Options no longer offered: gone, unless an order remembers them.
    update public.product_variants pv
       set is_active = false
     where pv.product_id = v_id
       and not (pv.id = any (v_variant_ids))
       and exists (select 1 from public.order_items oi where oi.variant_id = pv.id);
    delete from public.product_variants pv
     where pv.product_id = v_id
       and not (pv.id = any (v_variant_ids))
       and not exists (select 1 from public.order_items oi where oi.variant_id = pv.id);
  end if;

  -- 3b. Any other kind of variant (only when the payload carries them) --------
  if v_custom is not null then
    -- Pack/SS options have their own editor, which derives names and SKUs
    -- from the grid; this list must not take them over.
    if exists (
      select 1 from public.product_variants pv
       where pv.product_id = v_id and pv.is_active
         and pv.attributes <> '{}'::jsonb
         and not exists (select 1 from jsonb_object_keys(pv.attributes) k where k not in ('pack', 'ss', 'mm'))
    ) then
      raise exception 'admin_save_product: this product sells pack/stone-size options' using errcode = '22023';
    end if;

    -- Options (axes): an admin that does not know them must not rename the
    -- variants of a product that has some.
    if v_options is null and exists (select 1 from public.product_options where product_id = v_id) then
      raise exception 'admin_save_product: this product has options, send variant_options' using errcode = '22023';
    end if;
    if v_options is not null then
      if jsonb_array_length(v_options) > 3 then
        raise exception 'admin_save_product: at most 3 options' using errcode = '22023';
      end if;
      for v_opt in select value from jsonb_array_elements(v_options) loop
        if jsonb_typeof(v_opt) <> 'object'
           or coalesce(v_opt ->> 'id', '') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
          raise exception 'admin_save_product: an option needs an id' using errcode = '22023';
        end if;
        v_opt_id := (v_opt ->> 'id')::uuid;
        if v_opt_id = any (v_option_ids) then
          raise exception 'admin_save_product: duplicate option %', v_opt_id using errcode = '22023';
        end if;
        select product_id into v_owner from public.product_options where id = v_opt_id;
        if v_owner is not null and v_owner <> v_id then
          raise exception 'admin_save_product: option % belongs to another product', v_opt_id using errcode = '22023';
        end if;
        v_owner := null;
        if char_length(btrim(coalesce(v_opt ->> 'name', ''))) not between 1 and 60
           or char_length(btrim(coalesce(v_opt ->> 'name_en', ''))) > 60 then
          raise exception 'admin_save_product: an option needs a name of 1 to 60 characters' using errcode = '22023';
        end if;
        if jsonb_typeof(v_opt -> 'values') is distinct from 'array'
           or jsonb_array_length(v_opt -> 'values') not between 1 and 30 then
          raise exception 'admin_save_product: an option needs 1 to 30 values' using errcode = '22023';
        end if;
        for v_val in select value from jsonb_array_elements(v_opt -> 'values') loop
          if jsonb_typeof(v_val) <> 'object'
             or coalesce(v_val ->> 'id', '') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
            raise exception 'admin_save_product: an option value needs an id' using errcode = '22023';
          end if;
          v_val_id := (v_val ->> 'id')::uuid;
          if v_val_id = any (v_value_ids) then
            raise exception 'admin_save_product: duplicate option value %', v_val_id using errcode = '22023';
          end if;
          select option_id into v_owner from public.product_option_values where id = v_val_id;
          if v_owner is not null and v_owner <> v_opt_id then
            raise exception 'admin_save_product: option value % belongs to another option', v_val_id using errcode = '22023';
          end if;
          v_owner := null;
          if char_length(btrim(coalesce(v_val ->> 'name', ''))) not between 1 and 60
             or char_length(btrim(coalesce(v_val ->> 'name_en', ''))) > 60 then
            raise exception 'admin_save_product: an option value needs a name of 1 to 60 characters' using errcode = '22023';
          end if;
          if nullif(v_val ->> 'swatch', '') !~ '^#[0-9a-f]{6}$' then
            raise exception 'admin_save_product: invalid swatch colour' using errcode = '22023';
          end if;
          v_value_ids := array_append(v_value_ids, v_val_id);
          v_value_axis := v_value_axis || jsonb_build_object(v_val_id::text, v_axes);
          v_value_info := v_value_info || jsonb_build_object(v_val_id::text, jsonb_build_object(
            'name', btrim(v_val ->> 'name'),
            'name_en', coalesce(nullif(btrim(coalesce(v_val ->> 'name_en', '')), ''), btrim(v_val ->> 'name')),
            'swatch', nullif(v_val ->> 'swatch', '')));
        end loop;
        if (select count(distinct lower(btrim(e ->> 'name'))) from jsonb_array_elements(v_opt -> 'values') e)
           <> jsonb_array_length(v_opt -> 'values') then
          raise exception 'admin_save_product: two values of an option have the same name' using errcode = '22023';
        end if;
        v_option_ids := array_append(v_option_ids, v_opt_id);
        v_axes := v_axes + 1;
      end loop;
      if (select count(distinct lower(btrim(e ->> 'name'))) from jsonb_array_elements(v_options) e) <> v_axes then
        raise exception 'admin_save_product: two options have the same name' using errcode = '22023';
      end if;
    end if;

    -- With options, each variant is one combination (one value per axis, in
    -- axis order, each combination once); its name and colour dot are
    -- derived from its values, whatever the payload says.
    if v_axes > 0 then
      v_norm := '[]'::jsonb;
      for v_item in select value from jsonb_array_elements(v_custom) loop
        if jsonb_typeof(v_item) <> 'object' then
          raise exception 'admin_save_product: invalid variant' using errcode = '22023';
        end if;
        v_picked := v_item -> 'option_values';
        if jsonb_typeof(v_picked) is distinct from 'array' or jsonb_array_length(v_picked) <> v_axes
           or exists (select 1 from jsonb_array_elements(v_picked) with ordinality e(val, n)
                       where jsonb_typeof(e.val) <> 'string'
                          or (v_value_axis ->> lower(e.val #>> '{}')) is distinct from (e.n - 1)::text) then
          raise exception 'admin_save_product: a variant needs one value of each option' using errcode = '22023';
        end if;
        v_combo := (select string_agg(lower(val), ',' order by n)
                      from jsonb_array_elements_text(v_picked) with ordinality e(val, n));
        if v_combo = any (v_combos) then
          raise exception 'admin_save_product: the same combination twice' using errcode = '22023';
        end if;
        v_combos := array_append(v_combos, v_combo);
        v_norm := v_norm || jsonb_build_array(v_item || jsonb_build_object(
          'option_values', (select jsonb_agg(lower(val) order by n)
                              from jsonb_array_elements_text(v_picked) with ordinality e(val, n)),
          'name', (select string_agg(v_value_info -> lower(val) ->> 'name', ' · ' order by n)
                     from jsonb_array_elements_text(v_picked) with ordinality e(val, n)),
          'name_en', (select string_agg(v_value_info -> lower(val) ->> 'name_en', ' · ' order by n)
                        from jsonb_array_elements_text(v_picked) with ordinality e(val, n)),
          'swatch', (select v_value_info -> lower(val) ->> 'swatch'
                       from jsonb_array_elements_text(v_picked) with ordinality e(val, n)
                      where v_value_info -> lower(val) ->> 'swatch' is not null
                      order by n limit 1)));
      end loop;
      v_custom := v_norm;
    end if;

    -- Validate the whole list first, so the renames below never half-apply.
    for v_item in select value from jsonb_array_elements(v_custom) loop
      if jsonb_typeof(v_item) <> 'object' then
        raise exception 'admin_save_product: invalid variant' using errcode = '22023';
      end if;
      if coalesce(v_item ->> 'id', '') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
        raise exception 'admin_save_product: a variant needs an id' using errcode = '22023';
      end if;
      v_variant_id := (v_item ->> 'id')::uuid;
      if v_variant_id = any (v_custom_ids) then
        raise exception 'admin_save_product: duplicate variant %', v_variant_id using errcode = '22023';
      end if;
      select product_id into v_owner from public.product_variants where id = v_variant_id;
      if v_owner is not null and v_owner <> v_id then
        raise exception 'admin_save_product: variant % belongs to another product', v_variant_id using errcode = '22023';
      end if;
      v_owner := null;
      v_name_fr := btrim(coalesce(v_item ->> 'name', ''));
      if char_length(v_name_fr) not between 1 and 200 or char_length(btrim(coalesce(v_item ->> 'name_en', ''))) > 200 then
        raise exception 'admin_save_product: a variant needs a name of 1 to 200 characters' using errcode = '22023';
      end if;
      v_swatch := nullif(v_item ->> 'swatch', '');
      if v_swatch is not null and v_swatch !~ '^#[0-9a-f]{6}$' then
        raise exception 'admin_save_product: invalid swatch colour' using errcode = '22023';
      end if;
      v_vprice := nullif(v_item ->> 'price', '');
      if v_vprice is not null and v_vprice !~ '^\d{1,10}(\.\d{1,2})?$' then
        raise exception 'admin_save_product: invalid variant price' using errcode = '22023';
      end if;
      v_custom_ids := array_append(v_custom_ids, v_variant_id);
    end loop;
    v_variant_id := null;

    -- Variants no longer listed go first, so their SKUs and names are free for
    -- the list: deleted, unless an order remembers them (then deactivated).
    update public.product_variants pv
       set is_active = false
     where pv.product_id = v_id
       and not (pv.id = any (v_custom_ids))
       and exists (select 1 from public.order_items oi where oi.variant_id = pv.id);
    delete from public.product_variants pv
     where pv.product_id = v_id
       and not (pv.id = any (v_custom_ids))
       and not exists (select 1 from public.order_items oi where oi.variant_id = pv.id);

    -- The axes and their values, before the variants that point at them:
    -- those no longer listed go (with their links and their photos' link).
    if v_options is not null then
      delete from public.product_options where product_id = v_id and not (id = any (v_option_ids));
      v_position := 0;
      for v_opt in select value from jsonb_array_elements(v_options) loop
        v_opt_id := (v_opt ->> 'id')::uuid;
        insert into public.product_options (id, product_id, name, position)
        values (v_opt_id, v_id, btrim(v_opt ->> 'name'), v_position)
        on conflict (id) do update set name = excluded.name, position = excluded.position;
        if nullif(btrim(coalesce(v_opt ->> 'name_en', '')), '') is not null then
          insert into public.product_option_translations (option_id, locale, name, status)
          values (v_opt_id, 'en', btrim(v_opt ->> 'name_en'), 'published')
          on conflict (option_id, locale) do update set name = excluded.name, status = 'published';
        else
          delete from public.product_option_translations where option_id = v_opt_id and locale = 'en';
        end if;

        delete from public.product_option_values where option_id = v_opt_id and not (id = any (v_value_ids));
        v_vpos := 0;
        for v_val in select value from jsonb_array_elements(v_opt -> 'values') loop
          v_val_id := (v_val ->> 'id')::uuid;
          insert into public.product_option_values (id, option_id, name, swatch, position)
          values (v_val_id, v_opt_id, btrim(v_val ->> 'name'), nullif(v_val ->> 'swatch', ''), v_vpos)
          on conflict (id) do update
             set name = excluded.name, swatch = excluded.swatch, position = excluded.position;
          if nullif(btrim(coalesce(v_val ->> 'name_en', '')), '') is not null then
            insert into public.product_option_value_translations (value_id, locale, name, status)
            values (v_val_id, 'en', btrim(v_val ->> 'name_en'), 'published')
            on conflict (value_id, locale) do update set name = excluded.name, status = 'published';
          else
            delete from public.product_option_value_translations where value_id = v_val_id and locale = 'en';
          end if;
          v_vpos := v_vpos + 1;
        end loop;
        v_position := v_position + 1;
      end loop;
    end if;

    -- product_variants_name_unique is not deferrable: swapping two names in one
    -- save would collide halfway. Listed variants first take their id as a
    -- placeholder name; a kept inactive variant holding a name the list reuses
    -- is renamed out of the way (its orders keep their own copy of the name).
    update public.product_variants
       set name = id::text
     where product_id = v_id and id = any (v_custom_ids);
    update public.product_variants pv
       set name = left(pv.name, 190) || ' #' || left(pv.id::text, 8)
     where pv.product_id = v_id
       and not (pv.id = any (v_custom_ids))
       and pv.name in (select btrim(e ->> 'name') from jsonb_array_elements(v_custom) e);

    v_sku := (select sku from public.products where id = v_id);
    v_position := 0;

    for v_item in select value from jsonb_array_elements(v_custom) loop
      v_variant_id := (v_item ->> 'id')::uuid;
      v_name_fr := btrim(v_item ->> 'name');
      v_name_en := nullif(btrim(coalesce(v_item ->> 'name_en', '')), '');
      v_swatch  := nullif(v_item ->> 'swatch', '');
      v_vprice  := nullif(v_item ->> 'price', '');

      if exists (select 1 from public.product_variants where id = v_variant_id) then
        update public.product_variants
           set name       = v_name_fr,
               attributes = case when v_swatch is null then attributes - 'swatch'
                                 else attributes || jsonb_build_object('swatch', v_swatch) end,
               price      = v_vprice::numeric(12, 2),
               is_active  = true,
               position   = v_position
         where id = v_variant_id
        returning sku into v_vsku;
      else
        v_vsku := null;
        insert into public.product_variants (id, product_id, name, attributes, price, is_active, position)
        values (v_variant_id, v_id, v_name_fr,
                case when v_swatch is null then '{}'::jsonb else jsonb_build_object('swatch', v_swatch) end,
                v_vprice::numeric(12, 2), true, v_position);
      end if;

      -- SKU: set once, from the product SKU and the French name in plain
      -- ASCII (no unaccent extension needed), unique with a suffix.
      if v_vsku is null and v_sku is not null then
        v_code := upper(btrim(regexp_replace(
          translate(replace(replace(replace(replace(v_name_fr, 'œ', 'oe'), 'Œ', 'OE'), 'æ', 'ae'), 'Æ', 'AE'),
                    'àâäáãåçéèêëíìîïñóòôöõúùûüýÿÀÂÄÁÃÅÇÉÈÊËÍÌÎÏÑÓÒÔÖÕÚÙÛÜÝŸ',
                    'aaaaaaceeeeiiiinooooouuuuyyAAAAAACEEEEIIIINOOOOOUUUUYY'),
          '[^A-Za-z0-9]+', '-', 'g'), '-'));
        if v_code = '' then
          v_code := 'V' || (v_position + 1);
        end if;
        v_base := rtrim(left(v_sku || '-' || v_code, 60), '-');
        v_vsku := v_base;
        v_n := 1;
        while exists (select 1 from public.product_variants where sku = v_vsku and id <> v_variant_id) loop
          v_n := v_n + 1;
          v_vsku := v_base || '-' || v_n;
        end loop;
        update public.product_variants set sku = v_vsku where id = v_variant_id;
      end if;

      if v_name_en is not null then
        insert into public.product_variant_translations (variant_id, locale, name, status)
        values (v_variant_id, 'en', v_name_en, 'published')
        on conflict (variant_id, locale) do update set name = excluded.name, status = 'published';
      else
        delete from public.product_variant_translations where variant_id = v_variant_id and locale = 'en';
      end if;

      -- The value it has on each axis (validated above, in axis order).
      delete from public.product_variant_option_values where variant_id = v_variant_id;
      if v_axes > 0 then
        insert into public.product_variant_option_values (variant_id, option_id, value_id)
        select v_variant_id, v_option_ids[e.n], (e.val)::uuid
          from jsonb_array_elements_text(v_item -> 'option_values') with ordinality e(val, n);
      end if;

      update public.inventory_items
         set track_inventory     = coalesce((v_item ->> 'track_inventory')::boolean, track_inventory),
             quantity_on_hand    = coalesce((v_item ->> 'quantity_on_hand')::integer, quantity_on_hand),
             low_stock_threshold = coalesce((v_item ->> 'low_stock_threshold')::integer, low_stock_threshold)
       where variant_id = v_variant_id;
      if not found then
        insert into public.inventory_items (variant_id, track_inventory, quantity_on_hand, low_stock_threshold)
        values (v_variant_id,
                coalesce((v_item ->> 'track_inventory')::boolean, true),
                coalesce((v_item ->> 'quantity_on_hand')::integer, 0),
                coalesce((v_item ->> 'low_stock_threshold')::integer, 5));
      end if;

      v_variant_id := null;
      v_position := v_position + 1;
    end loop;
  end if;

  -- 4. Stock: one inventory row per product without active variants ---------
  --    A product with active variants keeps its stock on each variant (see
  --    step 3), and a digital product has none; both are left alone.
  if exists (select 1 from public.product_variants where product_id = v_id and is_active)
     or exists (select 1 from public.products where id = v_id and product_type = 'digital') then
    v_inventory := null;
  end if;

  if v_inventory is not null then
    update public.inventory_items
       set track_inventory     = coalesce((v_inventory ->> 'track_inventory')::boolean, track_inventory),
           quantity_on_hand    = coalesce((v_inventory ->> 'quantity_on_hand')::integer, quantity_on_hand),
           low_stock_threshold = coalesce((v_inventory ->> 'low_stock_threshold')::integer, low_stock_threshold),
           availability        = coalesce(v_inventory ->> 'availability', availability)
     where product_id = v_id;
    if not found then
      insert into public.inventory_items
        (product_id, track_inventory, quantity_on_hand, low_stock_threshold, availability)
      values
        (v_id,
         coalesce((v_inventory ->> 'track_inventory')::boolean, true),
         coalesce((v_inventory ->> 'quantity_on_hand')::integer, 0),
         coalesce((v_inventory ->> 'low_stock_threshold')::integer, 5),
         coalesce(v_inventory ->> 'availability', 'in_stock'));
    end if;
  end if;

  -- 5. Media: the payload is the complete, ordered list ------------------------
  v_position := 0;
  v_keep := array(
    select (e ->> 'id')::uuid
      from jsonb_array_elements(v_media) e
     where coalesce(e ->> 'id', '') <> ''
  );

  with gone as (
    delete from public.product_media
     where product_id = v_id and not (id = any (v_keep))
    returning storage_path
  )
  select array_agg(storage_path) into v_removed from gone;

  -- One primary per product (partial unique index): clear before re-setting.
  update public.product_media set is_primary = false where product_id = v_id and is_primary;

  for v_item in select value from jsonb_array_elements(v_media) loop
    -- The variant a photo shows: only a variant of this very product.
    v_media_variant := nullif(v_item ->> 'variant_id', '')::uuid;
    if v_media_variant is not null
       and not exists (select 1 from public.product_variants where id = v_media_variant and product_id = v_id) then
      raise exception 'admin_save_product: media variant % does not belong to this product', v_media_variant
        using errcode = '22023';
    end if;
    -- …or the option value it shows: only a value of this very product.
    v_media_value := nullif(v_item ->> 'option_value_id', '')::uuid;
    if v_media_value is not null
       and not exists (select 1 from public.product_option_values ov
                         join public.product_options o on o.id = ov.option_id
                        where ov.id = v_media_value and o.product_id = v_id) then
      raise exception 'admin_save_product: media option value % does not belong to this product', v_media_value
        using errcode = '22023';
    end if;
    if v_media_value is not null and v_media_variant is not null then
      raise exception 'admin_save_product: a photo shows a variant or an option value, not both' using errcode = '22023';
    end if;

    if coalesce(v_item ->> 'id', '') <> '' then
      update public.product_media
         set position   = v_position,
             is_primary = (v_position = 0),
             alt_text   = nullif(v_item ->> 'alt_fr', ''),
             variant_id = case when v_item ? 'variant_id' then v_media_variant
                               when v_media_value is not null then null
                               else variant_id end,
             option_value_id = case when v_item ? 'option_value_id' then v_media_value
                                    when v_media_variant is not null then null
                                    else option_value_id end
       where id = (v_item ->> 'id')::uuid and product_id = v_id
      returning id into v_media_id;
      if v_media_id is null then
        raise exception 'admin_save_product: media % does not belong to this product', v_item ->> 'id'
          using errcode = '22023';
      end if;
    else
      if coalesce(v_item ->> 'storage_path', '') !~ '^products/[A-Za-z0-9._/-]+$' then
        raise exception 'admin_save_product: invalid storage path' using errcode = '22023';
      end if;
      insert into public.product_media (product_id, variant_id, option_value_id, storage_path, alt_text, position, is_primary)
      values (v_id, v_media_variant, v_media_value, v_item ->> 'storage_path', nullif(v_item ->> 'alt_fr', ''), v_position, v_position = 0)
      returning id into v_media_id;
    end if;

    if coalesce(trim(v_item ->> 'alt_en'), '') <> '' then
      insert into public.product_media_translations (media_id, locale, alt_text, status)
      values (v_media_id, 'en', v_item ->> 'alt_en', 'published')
      on conflict (media_id, locale) do update
         set alt_text = excluded.alt_text, status = 'published';
    else
      delete from public.product_media_translations where media_id = v_media_id and locale = 'en';
    end if;

    v_media_id := null;
    v_position := v_position + 1;
  end loop;

  return jsonb_build_object(
    'id', v_id,
    'slug', (select slug from public.products where id = v_id),
    'removed_paths', to_jsonb(coalesce(array(
      select distinct path
        from unnest(v_removed) as path
       where path like 'products/%'
         and not exists (select 1 from public.product_media m where m.storage_path = path)
    ), '{}'::text[]))
  ) || case when v_variants is not null
            then jsonb_build_object('variants', to_jsonb(v_variant_ids))
            else '{}'::jsonb end
    || case when v_custom is not null
            then jsonb_build_object('custom_variants', to_jsonb(v_custom_ids))
            else '{}'::jsonb end
    || case when p_product ? 'family_id'
            then jsonb_build_object('family_id', (select family_id from public.products where id = v_id))
            else '{}'::jsonb end
    || case when v_specs is not null
            then jsonb_build_object('specs', true)
            else '{}'::jsonb end
    || case when v_options is not null
            then jsonb_build_object('variant_options', true)
            else '{}'::jsonb end;
end;
$$;

