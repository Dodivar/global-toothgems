if (proc?.argv?.[1]?.endsWith("authTemplates.ts")) {
  const { writeFileSync } = await import("node:fs");
  for (const t of TEMPLATES) {
    writeFileSync(new URL(`../../../templates/${t.file}`, import.meta.url), renderAuthTemplate(t));
    console.log(`wrote supabase/templates/${t.file}`);
  }
}
