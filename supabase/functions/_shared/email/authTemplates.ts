export function renderAuthTemplate(t: AuthTemplate): string {
  const blocks = [
    ...(t.eyebrow ? [eyebrow(t.eyebrow)] : []),
    title(t.title),
    intro(t.intro),
    actions({ label: t.button, url: LINK }),
    note(t.note),
  ];
  const { html } = emailDocument({ locale: "fr", subject: t.subject, preheader: t.intro, blocks }, layout);
  const body = html
    .replaceAll(LINK, "@@LINK@@")
    .replaceAll("@@LINK@@", GO.link(t.linkType))
    .replaceAll(FIRST_NAME, t.firstName === "suffix" ? GO.firstNameSuffix : GO.firstNameSpaced)
    .replaceAll(EMAIL, GO.email);
  return `<!--\n  ${t.comment}\n-->\n${body}\n`;
}

