// Stand-ins that survive the renderer's escaping and https checks, swapped for Go template actions afterwards.
const LINK = "https://auth-template.invalid/link";
const FIRST_NAME = "@@FIRST_NAME@@";
const EMAIL = "@@EMAIL@@";

const GO = {
  link: (type: string) => `{{ .RedirectTo }}&amp;token_hash={{ .TokenHash }}&amp;type=${type}`,
  firstNameSuffix: "{{ if .Data.first_name }}, {{ .Data.first_name }}{{ end }}",
  firstNameSpaced: "{{ if .Data.first_name }} {{ .Data.first_name }}{{ end }}",
  email: "{{ .Email }}",
};

function note(value: string): Block {
  return {
    html: `<p style="margin:16px 0 0;font-family:${fontStack}font-size:13px;line-height:1.6;color:${color.muted};">${escapeHtml(value)}</p>`,
    text: value,
  };
}

